// Generate site/abi.js (trimmed ABIs) from the compiled artifacts.
// Usage: node scripts/gen-site-abi.mjs   (after scripts/compile.mjs)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = JSON.parse(readFileSync(join(root, "artifacts", "AgentRollCall.json"), "utf8"));

const wanted = new Set([
  "checkIn", "claimBadge", "getUser", "badgeClaimed", "totalAgents",
  "totalCheckInsAll", "balanceOf", "CheckedIn", "BadgeClaimed",
]);
const abi = artifact.abi.filter((e) => wanted.has(e.name));

const registryAbi = [
  {
    type: "function", name: "balanceOf", stateMutability: "view",
    inputs: [{ name: "owner", type: "address" }],
    outputs: [{ name: "", type: "uint256" }],
  },
];

const out = `// Generated by scripts/gen-site-abi.mjs from artifacts/AgentRollCall.json — do not edit by hand.
const ROLLCALL_ABI = ${JSON.stringify(abi, null, 2)};

const AGENT_ID_REGISTRY_ABI = ${JSON.stringify(registryAbi, null, 2)};
`;
writeFileSync(join(root, "site", "abi.js"), out);
console.log(`site/abi.js written (${abi.length} entries)`);
